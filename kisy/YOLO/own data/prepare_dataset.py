#!/usr/bin/env python3
"""Step 3 - build a YOLO dataset from the Roboflow COCO export.

Reads "kisy-Folder- frames - Auto Label.coco" (never modifies it) and writes:
    dataset/images/{train,val}/*.jpg
    dataset/labels/{train,val}/*.txt   (YOLO: cls cx cy w h, normalised)
    dataset/data.yaml
Random ~80/20 split over all 1007 images, merged from Roboflow's own split.
"""
import json, random, shutil, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SRC = ROOT / "kisy-Folder- frames - Auto Label.coco"
OUT = ROOT / "dataset"
CLASS_MAP = {"Bottle": 0, "Pen": 1}      # coco name -> class id
IGNORED = {"kisy"}                        # stray class from the auto-label tool
VAL_FRAC, SEED = 0.2, 42
SPLITS = ("train", "valid", "test")

items, seen = [], set()
st = {"boxes": {0: 0, 1: 0}, "ignored": 0, "clipped": 0,
      "missing": 0, "dupes": 0, "unknown": set()}

for split in SPLITS:
    ann = SRC / split / "_annotations.coco.json"
    if not ann.exists():
        print(f"  ! no annotations in {split}/"); continue
    coco = json.loads(ann.read_text())
    cat = {c["id"]: c["name"] for c in coco["categories"]}
    st["unknown"] |= set(cat.values()) - set(CLASS_MAP) - IGNORED
    by_img = {}
    for a in coco["annotations"]:
        by_img.setdefault(a["image_id"], []).append(a)
    for img in coco["images"]:
        jpg = SRC / split / img["file_name"]
        if not jpg.exists():
            st["missing"] += 1; continue
        # one source frame can appear once only - keep the first copy
        key = img.get("extra", {}).get("name", img["file_name"])
        if key in seen:
            st["dupes"] += 1; continue
        seen.add(key)
        W, H = img["width"], img["height"]
        boxes = []
        for a in by_img.get(img["id"], []):
            name = cat[a["category_id"]]
            if name in IGNORED:
                st["ignored"] += 1; continue
            x, y, w, h = a["bbox"]
            if w <= 0 or h <= 0: continue
            x1, y1 = max(0.0, x), max(0.0, y)
            x2, y2 = min(float(W), x + w), min(float(H), y + h)
            if x2 <= x1 or y2 <= y1: continue
            if (x1, y1, x2, y2) != (float(x), float(y), x + w, y + h):
                st["clipped"] += 1
            cid = CLASS_MAP[name]
            boxes.append((cid, (x1 + x2) / 2 / W, (y1 + y2) / 2 / H,
                          (x2 - x1) / W, (y2 - y1) / H))
            st["boxes"][cid] += 1
        items.append((jpg, boxes))

if st["unknown"]:
    sys.exit(f"! unknown categories {st['unknown']} - aborting")
if not items:
    sys.exit("! no images found")

random.Random(SEED).shuffle(items)
n_val = round(len(items) * VAL_FRAC)
val, train = items[:n_val], items[n_val:]

if OUT.exists(): shutil.rmtree(OUT)
for part, rows in (("train", train), ("val", val)):
    (OUT / "images" / part).mkdir(parents=True)
    (OUT / "labels" / part).mkdir(parents=True)
    for jpg, boxes in rows:
        shutil.copy2(jpg, OUT / "images" / part / jpg.name)
        (OUT / "labels" / part / (jpg.stem + ".txt")).write_text(
            "".join(f"{c} {cx:.6f} {cy:.6f} {w:.6f} {h:.6f}\n" for c, cx, cy, w, h in boxes))

(OUT / "data.yaml").write_text(
    f"# data.yaml - YOLO dataset config (generated by prepare_dataset.py)\n"
    f"path: {OUT}\ntrain: images/train\nval: images/val\n"
    f"nc: {len(CLASS_MAP)}\nnames: [{', '.join(k.lower() for k in CLASS_MAP)}]\n")

# --- verify what we just wrote ---
bad = 0
n_img = n_lbl = 0
for part in ("train", "val"):
    imgs = {p.stem for p in (OUT / "images" / part).glob("*.jpg")}
    lbls = {p.stem for p in (OUT / "labels" / part).glob("*.txt")}
    n_img += len(imgs); n_lbl += len(lbls)
    if imgs != lbls: bad += 1
    for p in (OUT / "labels" / part).glob("*.txt"):
        for line in p.read_text().splitlines():
            f = line.split()
            if len(f) != 5 or not all(0 <= float(v) <= 1 for v in f[1:]):
                print(f"  ! bad line in {p.name}: {line}"); bad += 1
print(f"train images {len(train)} | val images {len(val)} | total {len(items)}")
print(f"boxes: bottle(class 0)={st['boxes'][0]} pen(class 1)={st['boxes'][1]}")
print(f"images without boxes: {sum(1 for _, b in items if not b)}")
print(f"ignored '{'/'.join(IGNORED)}' boxes: {st['ignored']} | clipped: {st['clipped']} "
      f"| dupes skipped: {st['dupes']} | missing: {st['missing']}")
print(f"verify: images={n_img} labels={n_lbl} mismatched-dirs={bad}")
